#!/usr/bin/env python3
"""Builds src/ca_bundle.h: the roots trusted by Mozilla (the same list browsers use, from the
certifi package) in the compact binary format of WiFiClientSecure::setCACertBundle() (same as
ESP-IDF's gen_crt_bundle.py). With a bundle, each HTTPS connection parses only the one root that
signed the server, instead of a whole PEM list: ~20-30 KB less RAM per request, and any site works.

  pip install certifi cryptography && python3 tools/gen_ca_bundle.py
"""
import re, warnings
import certifi
from cryptography import x509
from cryptography.hazmat.primitives import serialization

warnings.filterwarnings("ignore")
src = open(certifi.where()).read() + open("tools/extra_roots.pem").read()   # + retired roots still used in cross-signs
pems = re.findall(r"-----BEGIN CERTIFICATE-----.*?-----END CERTIFICATE-----", src, re.S)
entries = []
for p in pems:
    c = x509.load_pem_x509_certificate(p.encode())
    name = c.subject.public_bytes()
    key = c.public_key().public_bytes(serialization.Encoding.DER, serialization.PublicFormat.SubjectPublicKeyInfo)
    entries.append((name, key, c.subject.rfc4514_string()))
entries = list({e[0]: e for e in entries}.values())   # one entry per subject
entries.sort(key=lambda e: e[0])                      # the board does a binary search by subject
blob = bytearray(len(entries).to_bytes(2, "big"))
for name, key, _ in entries:
    blob += len(name).to_bytes(2, "big") + len(key).to_bytes(2, "big") + name + key
lines = [f"// Generated by tools/gen_ca_bundle.py from certifi {certifi.__version__} (Mozilla roots) + tools/extra_roots.pem. Do not edit.",
         "#pragma once", "#include <pgmspace.h>",
         f"static const uint8_t CA_BUNDLE[{len(blob)}] PROGMEM = {{"]
for i in range(0, len(blob), 20):
    lines.append("  " + ", ".join(f"0x{b:02x}" for b in blob[i:i + 20]) + ",")
lines.append("};")
open("src/ca_bundle.h", "w").write("\n".join(lines) + "\n")
print(len(entries), "roots,", len(blob), "bytes")
