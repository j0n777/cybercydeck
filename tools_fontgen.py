#!/usr/bin/env python3
"""Generate LovyanGFX-compatible VLW (smooth, anti-aliased) fonts as C arrays.

VLW layout (big-endian int32):
  header: glyphCount, version(11), fontSize, 0, ascent, descent
  per glyph: unicode, height, width, xAdvance, dY(top above baseline), dX(left), 0
  then each glyph bitmap (width*height bytes, 8-bit alpha) in glyph order.
"""
import struct
import sys
import freetype

ASCII = list(range(0x20, 0x7F))
# Portuguese and Spanish letters plus the few symbols the UI uses; weather places and agent
# text arrive from the network, so all accented vowels stay, the rest of Latin-1 goes.
LATIN = [ord(c) for c in 'áàâãäéèêëíìîïóòôõöúùûüçñÁÀÂÃÄÉÈÊËÍÌÎÏÓÒÔÕÖÚÙÛÜÇÑ°ºª·«»×']
SYMBOLS = [0x2013, 0x2014, 0x2022, 0x2026, 0x2039, 0x203A, 0x2212]
CODEPOINTS = ASCII + LATIN + SYMBOLS
BIG = ASCII + [0xB0] + SYMBOLS                                   # clock, counters, pairing code
HUGE = [ord(c) for c in ' 0123456789.,:%+-'] + [0xB0, 0x2014, 0x2026, 0x2212]   # BTC price, temperature


def build(ttf, px, name, cps=None):
    face = freetype.Face(ttf)
    face.set_pixel_sizes(0, px)
    glyphs = []
    for cp in (cps or CODEPOINTS):
        if face.get_char_index(cp) == 0 and cp != 0x20:
            continue
        face.load_char(cp, freetype.FT_LOAD_RENDER | freetype.FT_LOAD_TARGET_NORMAL)
        g = face.glyph
        bm = g.bitmap
        w, h = bm.width, bm.rows
        pitch = bm.pitch
        data = bytearray()
        for row in range(h):
            data += bytes(bm.buffer[row * pitch: row * pitch + w])
        glyphs.append((cp, h, w, g.advance.x >> 6, g.bitmap_top, g.bitmap_left, bytes(data)))
    glyphs.sort(key=lambda t: t[0])
    ascent = face.size.ascender >> 6
    descent = -(face.size.descender >> 6)
    out = bytearray(struct.pack('>6i', len(glyphs), 11, px, 0, ascent, descent))
    for cp, h, w, adv, dy, dx, _ in glyphs:
        out += struct.pack('>7i', cp, h, w, adv, dy, dx, 0)
    for *_, data in glyphs:
        out += data
    lines = []
    for i in range(0, len(out), 24):
        lines.append(','.join('0x%02x' % b for b in out[i:i + 24]))
    body = ',\n'.join(lines)
    return f"// {ttf} {px}px, {len(glyphs)} glyphs, {len(out)} bytes\nconst uint8_t {name}[] PROGMEM = {{\n{body}\n}};\n", len(out)


if __name__ == '__main__':
    specs = [
        ('fonts/Barlow-Medium.ttf', 11, 'F_BM11'),
        ('fonts/Barlow-Medium.ttf', 13, 'F_BM13'),
        ('fonts/Barlow-SemiBold.ttf', 13, 'F_BS13'),
        ('fonts/Barlow-SemiBold.ttf', 16, 'F_BS16'),
        ('fonts/ChakraPetch-SemiBold.ttf', 12, 'F_CS12'),
        ('fonts/ChakraPetch-Bold.ttf', 18, 'F_CB18'),
        ('fonts/ChakraPetch-Bold.ttf', 24, 'F_CB24'),
        ('fonts/ChakraPetch-Bold.ttf', 34, 'F_CB34', BIG),
        ('fonts/ChakraPetch-Bold.ttf', 46, 'F_CB46', HUGE),
    ]
    total = 0
    parts = ['#pragma once\n#include <Arduino.h>\n// Generated by fontgen.py. Barlow and Chakra Petch are SIL Open Font License 1.1.\n']
    for ttf, px, name, *cps in specs:
        src, n = build(ttf, px, name, cps[0] if cps else None)
        parts.append(src)
        total += n
        print(name, n, file=sys.stderr)
    open(sys.argv[1], 'w').write('\n'.join(parts))
    print('total bytes', total, file=sys.stderr)
