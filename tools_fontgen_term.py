#!/usr/bin/env python3
"""IBM Plex Mono (SIL OFL 1.1) as VLW arrays for the Terminal themes. Uses build() from tools_fontgen.py."""
import sys
import tools_fontgen
from tools_fontgen import build

SPECS = [
    ('fonts/IBMPlexMono-Regular.ttf', 10, 'T_BM11'),
    ('fonts/IBMPlexMono-Medium.ttf', 12, 'T_BM13'),
    ('fonts/IBMPlexMono-SemiBold.ttf', 12, 'T_BS13'),
    ('fonts/IBMPlexMono-SemiBold.ttf', 15, 'T_BS16'),
    ('fonts/IBMPlexMono-SemiBold.ttf', 11, 'T_CS12'),
    ('fonts/IBMPlexMono-Bold.ttf', 17, 'T_CB18'),
    ('fonts/IBMPlexMono-Bold.ttf', 22, 'T_CB24'),
    ('fonts/IBMPlexMono-Bold.ttf', 31, 'T_CB34'),   # ASCII only (clock, prices, percentages)
]
if __name__ == '__main__':
    parts = ['#pragma once\n#include <Arduino.h>\n// Generated by tools_fontgen_term.py. IBM Plex Mono is SIL Open Font License 1.1.\n']
    total = 0
    for ttf, px, name in SPECS:
        src, n = build(ttf, px, name, tools_fontgen.BIG if name == 'T_CB34' else None)
        parts.append(src); total += n
        print(name, n, file=sys.stderr)
    open(sys.argv[1], 'w').write('\n'.join(parts))
    print('total bytes', total, file=sys.stderr)
